    assert.equal((await describePath(codex)).type, 'link');
    assert.match(await readFile(path.join(claude, 'SKILL.md'), 'utf8'), /Original body/);
    await rollbackBackup({ backupId: result.backupId, root: fixture.repo, stateRoot: fixture.state, roots: fixture.roots });
