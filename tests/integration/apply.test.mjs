// Every managed shared-link skill installs as a junction, so a retirement whose preimage
// must be a directory can never name one. This is the case that dead-ended before the
// planner accepted a link preimage.
test('a retired skill link is quarantined, not deleted, and rollback restores the junction', async () => {
  const fixture = await makeFixture({ setup: async ({ repo }) => addSkill(repo, 'demo') });
  try {
    const installed = await calculatePlan({ root: fixture.repo, stateRoot: fixture.state, artifactIds: ['skills.demo'], roots: fixture.roots });
    await applyPlan({ planPath: installed.planPath, root: fixture.repo, stateRoot: fixture.state, roots: fixture.roots });
    const claude = path.join(fixture.userHome, '.claude', 'skills', 'demo');
    const codex = path.join(fixture.userHome, '.agents', 'skills', 'demo');
    assert.equal((await describePath(claude)).type, 'link');
    assert.equal((await describePath(codex)).type, 'link');

    await rm(path.join(fixture.repo, 'skills', 'demo'), { recursive: true });
    const manifestPath = path.join(fixture.repo, 'manifest.json');
    const manifest = JSON.parse(await readFile(manifestPath, 'utf8'));
    manifest.artifacts.push({
      id: 'legacy.retire-demo', kind: 'legacy-retirement', ownership: 'provider-only',
      platforms: ['windows', 'macos'], providers: ['claude', 'codex'], risk: 'control-confirm',
      source: ['migration-fixture.json'],
      legacyTargets: [
        { provider: 'claude', path: '${USER_HOME}/.claude/skills/demo' },
        { provider: 'codex', path: '${USER_HOME}/.agents/skills/demo' },
      ],
      validators: ['known-preimage-only'],
    });
    await writeFile(path.join(fixture.repo, 'migration-fixture.json'), '{"fixture":true}\n', 'utf8');
    await writeFile(manifestPath, `${JSON.stringify(manifest, null, 2)}\n`, 'utf8');
    await validateRepository(fixture.repo, { writeLock: true });
    fixtureCommit(fixture.repo, 'retire demo');

    const retirement = await calculatePlan({ root: fixture.repo, stateRoot: fixture.state, artifactIds: ['legacy.retire-demo'], roots: fixture.roots });
    assert.equal(retirement.plan.operations.length, 2);
    for (const operation of retirement.plan.operations) {
      assert.equal(operation.type, 'quarantine-known-directory');
      assert.equal(operation.preimage.type, 'link');
      assert.equal(operation.postimage.type, 'absent');
    }
    const result = await applyPlan({ planPath: retirement.planPath, root: fixture.repo, stateRoot: fixture.state, roots: fixture.roots, confirmationPlanId: retirement.plan.planId });
    assert.equal(await pathExists(claude), false);
    assert.equal(await pathExists(codex), false);

    await rollbackBackup({ backupId: result.backupId, root: fixture.repo, stateRoot: fixture.state, roots: fixture.roots });
    assert.equal((await describePath(claude)).type, 'link');
    assert.equal((await describePath(codex)).type, 'link');
  } finally { await fixture.cleanup(); }
});

