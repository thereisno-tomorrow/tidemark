async function combineMarkdown(files, title) {
  const sections = [];
  for (const file of files) {
    const content = (await readFile(file, 'utf8')).trim();
    if (content) sections.push(content);
  }
  return `<!-- Generated by agent-config ${TOOL_VERSION}; edit canonical source, not this file. -->\n\n# ${title}\n\n${sections.join('\n\n---\n\n')}\n`;
}

function tomlString(value) {
  return JSON.stringify(String(value));
}

function expandKnownTokens(value, roots = {}) {
  if (Array.isArray(value)) return value.map((item) => expandKnownTokens(item, roots));
  if (value && typeof value === 'object') return Object.fromEntries(Object.entries(value).map(([key, child]) => [key, expandKnownTokens(child, roots)]));
  if (typeof value !== 'string') return value;
  return value.replace(/\$\{([A-Z_]+)\}/g, (match, key) => Object.hasOwn(roots, key) ? roots[key] : match);
}

function renderMcpToml(server, roots) {
  const lines = [`[mcp_servers.${server.id}]`];
  if (server.transport === 'http') lines.push(`url = ${tomlString(expandKnownTokens(server.url, roots))}`);
  else {
    lines.push(`command = ${tomlString(expandKnownTokens(server.command, roots))}`);
    lines.push(`args = ${JSON.stringify(expandKnownTokens(server.args ?? [], roots))}`);
    const environment = expandKnownTokens(server.environment ?? {}, roots);
    if (Object.keys(environment).length) {
      lines.push('', `[mcp_servers.${server.id}.env]`);
      for (const [key, value] of Object.entries(environment).sort()) lines.push(`${key} = ${tomlString(value)}`);
    }
  }
  if (server.enabledTools?.length) lines.splice(1, 0, `enabled_tools = ${JSON.stringify(server.enabledTools)}`);
  if (server.approvalMode) lines.splice(1, 0, `default_tools_approval_mode = ${tomlString(server.approvalMode)}`);
  return lines.join('\n');
}

function stripManagedCodexBlock(content) {
  return content.replace(/\r?\n?# BEGIN agent-config managed mcp\r?\n[\s\S]*?\r?\n# END agent-config managed mcp\r?\n?/g, '\n').trimEnd();
}

function parseCodexHooks(content, label) {
  let parsed;
  try { parsed = JSON.parse(content); }
  catch (error) {
    throw new AgentConfigError('CODEX_HOOKS_INVALID', label + ' is not valid JSON', { cause: error.message });
  }
  if (!parsed || Array.isArray(parsed) || typeof parsed !== 'object') {
    throw new AgentConfigError('CODEX_HOOKS_INVALID', label + ' must be a JSON object');
  }
  const unknown = Object.keys(parsed).filter((key) => !['description', 'hooks'].includes(key));
  if (unknown.length) {
    throw new AgentConfigError('CODEX_HOOKS_INVALID', label + ' contains unsupported top-level fields', { fields: unknown });
  }
  if (parsed.description !== undefined && typeof parsed.description !== 'string') {
    throw new AgentConfigError('CODEX_HOOKS_INVALID', label + ' description must be a string');
  }
  if (!parsed.hooks || Array.isArray(parsed.hooks) || typeof parsed.hooks !== 'object') {
    throw new AgentConfigError('CODEX_HOOKS_INVALID', label + ' hooks must be an object');
  }
  for (const [event, groups] of Object.entries(parsed.hooks)) {
    if (!Array.isArray(groups)) throw new AgentConfigError('CODEX_HOOKS_INVALID', label + ' event must be an array: ' + event);
    for (const group of groups) {
      if (!group || Array.isArray(group) || typeof group !== 'object' || !Array.isArray(group.hooks)) {
        throw new AgentConfigError('CODEX_HOOKS_INVALID', label + ' contains an invalid matcher group: ' + event);
      }
      if (group.matcher !== undefined && typeof group.matcher !== 'string') {
        throw new AgentConfigError('CODEX_HOOKS_INVALID', label + ' matcher must be a string: ' + event);
      }
      if (group.hooks.some((handler) => !handler || Array.isArray(handler) || typeof handler !== 'object' || typeof handler.type !== 'string')) {
        throw new AgentConfigError('CODEX_HOOKS_INVALID', label + ' contains an invalid hook handler: ' + event);
      }
    }
  }
  return parsed;
}

function parseClaudeSettings(content, label) {
  let parsed;
  try { parsed = JSON.parse(content); }
  catch (error) {
    throw new AgentConfigError('CLAUDE_SETTINGS_INVALID', label + ' is not valid JSON', { cause: error.message });
  }
  if (!parsed || Array.isArray(parsed) || typeof parsed !== 'object') {
    throw new AgentConfigError('CLAUDE_SETTINGS_INVALID', label + ' must be a JSON object');
  }
  validateHookMap(parsed.hooks ?? {}, label, 'CLAUDE_SETTINGS_INVALID');
  return parsed;
}

function validateHookMap(hooks, label, code) {
  if (!hooks || Array.isArray(hooks) || typeof hooks !== 'object') {
    throw new AgentConfigError(code, label + ' hooks must be an object');
  }
  for (const [event, groups] of Object.entries(hooks)) {
    if (!Array.isArray(groups)) throw new AgentConfigError(code, label + ' event must be an array: ' + event);
    for (const group of groups) {
      if (!group || Array.isArray(group) || typeof group !== 'object' || !Array.isArray(group.hooks)) {
        throw new AgentConfigError(code, label + ' contains an invalid matcher group: ' + event);
      }
      if (group.matcher !== undefined && typeof group.matcher !== 'string') {
        throw new AgentConfigError(code, label + ' matcher must be a string: ' + event);
      }
      if (group.hooks.some((handler) => !handler || Array.isArray(handler) || typeof handler !== 'object' || typeof handler.type !== 'string')) {
        throw new AgentConfigError(code, label + ' contains an invalid hook handler: ' + event);
      }
    }
  }
}

const ABSENT = Symbol('absent');

function isPlainObject(value) {
  return value !== ABSENT && value !== null && !Array.isArray(value) && typeof value === 'object';
}

function sameManagedValue(left, right) {
  if (left === ABSENT || right === ABSENT) return left === right;
  return canonicalize(left) === canonicalize(right);
}

function cloneManagedValue(value) {
  return value === ABSENT ? ABSENT : structuredClone(value);
}

function claudeMergeConflict(pathParts, message) {
  const setting = pathParts.length ? pathParts.join('.') : '<root>';
  throw new AgentConfigError('CLAUDE_SETTINGS_MERGE_CONFLICT', message + ': ' + setting, { setting });
}

function mergeManagedNode(previous, current, next, pathParts, { currentExists }) {
  const strictSubtree = pathParts[0] === 'permissions';
  const objectMerge = !strictSubtree && (isPlainObject(previous) || isPlainObject(next));

  if (objectMerge) {
    if (current !== ABSENT && !isPlainObject(current)) {
      claudeMergeConflict(pathParts, 'A managed Claude setting was replaced with an incompatible native value');
    }
    const previousObject = isPlainObject(previous) ? previous : {};
    const currentObject = isPlainObject(current) ? current : {};
    const nextObject = isPlainObject(next) ? next : {};
    const output = structuredClone(currentObject);
    const managedKeys = new Set([...Object.keys(previousObject), ...Object.keys(nextObject)]);
    for (const key of managedKeys) {
      const merged = mergeManagedNode(
        Object.hasOwn(previousObject, key) ? previousObject[key] : ABSENT,
        Object.hasOwn(currentObject, key) ? currentObject[key] : ABSENT,
        Object.hasOwn(nextObject, key) ? nextObject[key] : ABSENT,
        [...pathParts, key],
        { currentExists },
      );
      if (merged === ABSENT) delete output[key];
      else output[key] = merged;
    }
    if (next === ABSENT && !Object.keys(output).length) return ABSENT;
    return output;
  }

  if (previous === ABSENT) {
    if (next === ABSENT) return cloneManagedValue(current);
    if (current === ABSENT || sameManagedValue(current, next)) return cloneManagedValue(next);
    claudeMergeConflict(pathParts, 'A native Claude setting conflicts with a newly managed value');
  }
  if (next === ABSENT) {
    if (current === ABSENT || sameManagedValue(current, previous)) return ABSENT;
    claudeMergeConflict(pathParts, 'A managed Claude setting was modified before removal');
  }
  if (current === ABSENT) {
    if (!currentExists) return cloneManagedValue(next);
    claudeMergeConflict(pathParts, 'A managed Claude setting is missing');
  }
  if (sameManagedValue(current, previous) || sameManagedValue(current, next)) return cloneManagedValue(next);
  claudeMergeConflict(pathParts, 'A managed Claude setting was modified outside agent-config');
}

function handlerIdentity(handler) {
  if (handler.type === 'command') {
    return canonicalize({ type: handler.type, command: handler.command ?? null, commandWindows: handler.commandWindows ?? null });
  }
  if (handler.type === 'mcp_tool') {
    return canonicalize({ type: handler.type, server: handler.server ?? null, tool: handler.tool ?? null, input: handler.input ?? {} });
  }
  return canonicalize({ type: handler.type });
}

function managedGroupKey(group) {
  return canonicalize({ matcher: group.matcher ?? null, handlers: group.hooks.map(handlerIdentity) });
}

function groupsOverlap(left, right) {
  if ((left.matcher ?? null) !== (right.matcher ?? null)) return false;
  const identities = new Set(left.hooks.map(handlerIdentity));
  return right.hooks.some((handler) => identities.has(handlerIdentity(handler)));
}

function assertUniqueManagedGroups(groups, event, label, code) {
  const keys = new Set();
  for (const group of groups) {
    const key = managedGroupKey(group);
    if (keys.has(key)) throw new AgentConfigError(code, label + ' repeats a managed hook group: ' + event);
    keys.add(key);
  }
}

function mergeHookMaps(previousHooks, currentHooks, nextHooks, {
  invalidCode,
  conflictCode,
  integrationName,
}) {
  const merged = structuredClone(currentHooks ?? {});
  const events = new Set([
    ...Object.keys(previousHooks ?? {}),
    ...Object.keys(currentHooks ?? {}),
    ...Object.keys(nextHooks ?? {}),
  ]);
  for (const event of events) {
    const previous = previousHooks?.[event] ?? [];
    const next = nextHooks?.[event] ?? [];
    const output = structuredClone(currentHooks?.[event] ?? []);
    assertUniqueManagedGroups(previous, event, 'previous managed ' + integrationName + ' hooks', invalidCode);
    assertUniqueManagedGroups(next, event, 'next managed ' + integrationName + ' hooks', invalidCode);
    const nextByKey = new Map(next.map((group) => [managedGroupKey(group), group]));
    const consumed = new Set();

    for (const previousGroup of previous) {
      const signature = canonicalize(previousGroup);
      const exact = output.map((group, index) => canonicalize(group) === signature ? index : -1).filter((index) => index >= 0);
      if (exact.length > 1) {
        throw new AgentConfigError(conflictCode, 'Managed ' + integrationName + ' hook appears more than once: ' + event);
      }
      const key = managedGroupKey(previousGroup);
      if (exact.length === 1) {
        const replacement = nextByKey.get(key);
        output[exact[0]] = replacement ? structuredClone(replacement) : null;
        if (replacement) consumed.add(key);
        continue;
      }
      if (output.some((group) => group && groupsOverlap(group, previousGroup))) {
        throw new AgentConfigError(conflictCode, 'A managed ' + integrationName + ' hook was modified outside agent-config: ' + event);
      }
    }

    for (const nextGroup of next) {
      const key = managedGroupKey(nextGroup);
      if (consumed.has(key)) continue;
      const signature = canonicalize(nextGroup);
      if (output.some((group) => group && canonicalize(group) === signature)) {
        consumed.add(key);
        continue;
      }
      if (output.some((group) => group && groupsOverlap(group, nextGroup))) {
        throw new AgentConfigError(conflictCode, 'A native ' + integrationName + ' hook conflicts with a managed hook: ' + event);
      }
      output.push(structuredClone(nextGroup));
      consumed.add(key);
    }

    const kept = output.filter(Boolean);
    if (kept.length) merged[event] = kept;
    else delete merged[event];
  }
  return merged;
}

export function mergeCodexHooks(previousManaged, currentNative, nextManaged, { currentExists = true } = {}) {
  const merged = structuredClone(currentNative);
  merged.hooks = mergeHookMaps(previousManaged.hooks, currentNative.hooks, nextManaged.hooks, {
    invalidCode: 'CODEX_HOOKS_INVALID',
    conflictCode: 'CODEX_HOOK_MERGE_CONFLICT',
    integrationName: 'Codex',
  });
  if (!currentExists || currentNative.description === previousManaged.description) {
    if (nextManaged.description === undefined) delete merged.description;
    else merged.description = nextManaged.description;
  }
  return merged;
}

export function mergeClaudeSettings(previousManaged, currentNative, nextManaged, { currentExists = true } = {}) {
  const previousSettings = structuredClone(previousManaged);
  const currentSettings = structuredClone(currentNative);
  const nextSettings = structuredClone(nextManaged);
  const previousHooks = previousSettings.hooks ?? {};
  const currentHooks = currentSettings.hooks ?? {};
  const nextHooks = nextSettings.hooks ?? {};
  delete previousSettings.hooks;
  delete currentSettings.hooks;
  delete nextSettings.hooks;

  const merged = mergeManagedNode(previousSettings, currentSettings, nextSettings, [], { currentExists });
  const hooks = mergeHookMaps(previousHooks, currentHooks, nextHooks, {
    invalidCode: 'CLAUDE_SETTINGS_INVALID',
    conflictCode: 'CLAUDE_SETTINGS_MERGE_CONFLICT',
    integrationName: 'Claude',
  });
  if (Object.keys(hooks).length) merged.hooks = hooks;
  else delete merged.hooks;
  return merged;
}

async function loadCodexHooks(file, label, { optional = false } = {}) {
  if (!await pathExists(file)) {
    if (optional) return null;
    throw new AgentConfigError('CODEX_HOOKS_INVALID', label + ' is missing');
  }
  return parseCodexHooks(await readFile(file, 'utf8'), label);
}

async function loadClaudeSettings(file, label, { optional = false } = {}) {
  if (!await pathExists(file)) {
    if (optional) return null;
    throw new AgentConfigError('CLAUDE_SETTINGS_INVALID', label + ' is missing');
  }
  return parseClaudeSettings(await readFile(file, 'utf8'), label);
}

async function loadClaudeManaged(sourceRoot, roots, label, { optional = false } = {}) {
  const settingsPath = path.join(sourceRoot, 'providers', 'claude', 'settings.patch.json');
  const mappingsPath = path.join(sourceRoot, 'hooks', 'mappings.json');
  const settingsExists = await pathExists(settingsPath);
  const mappingsExists = await pathExists(mappingsPath);
  if (!settingsExists && !mappingsExists && optional) return null;
  if (!settingsExists || !mappingsExists) {
    throw new AgentConfigError('CLAUDE_SETTINGS_INVALID', label + ' is incomplete');
  }

  let settings;
  let mappings;
  try {
    settings = JSON.parse(await readFile(settingsPath, 'utf8'));
    mappings = JSON.parse(await readFile(mappingsPath, 'utf8'));
  } catch (error) {
    throw new AgentConfigError('CLAUDE_SETTINGS_INVALID', label + ' contains invalid JSON', { cause: error.message });
  }
  if (settings.mergePolicy !== 'preserve-unmanaged') {
    throw new AgentConfigError('CLAUDE_SETTINGS_INVALID', label + ' must declare mergePolicy preserve-unmanaged');
  }
  if (!isPlainObject(settings.patch)) {
    throw new AgentConfigError('CLAUDE_SETTINGS_INVALID', label + ' patch must be an object');
  }
  const hooks = mappings.providers?.claude ?? {};
  validateHookMap(hooks, label, 'CLAUDE_SETTINGS_INVALID');
  return expandKnownTokens({ ...settings.patch, hooks }, roots);
}

async function generateProviderControl(sourceRoot, distRoot, roots, artifactIds) {
  let registry = null;
  const loadMcpRegistry = async () => {
    if (!registry) registry = JSON.parse(await readFile(path.join(sourceRoot, 'mcp', 'servers.json'), 'utf8'));
    return registry;
  };

  if (artifactIds.includes('provider.claude-settings')) {
    const previousRoot = path.join(roots.AGENT_CONFIG_STATE_ROOT, 'active', 'source');
    const nativePath = path.join(roots.USER_HOME, '.claude', 'settings.json');
    const previous = await loadClaudeManaged(previousRoot, roots, 'previous managed Claude settings', { optional: true });
    const current = await loadClaudeSettings(nativePath, 'native Claude settings', { optional: true });
    const next = await loadClaudeManaged(sourceRoot, roots, 'next managed Claude settings');
    const merged = mergeClaudeSettings(previous ?? {}, current ?? {}, next, { currentExists: current !== null });
    await atomicWrite(path.join(distRoot, 'claude', 'settings.json'), canonicalize(merged));
  }

  // Claude MCP registration is not supported in v1.

  if (artifactIds.includes('provider.codex-config')) {
    const nativePath = path.join(roots.USER_HOME, '.codex', 'config.toml');
    const native = await pathExists(nativePath) ? await readFile(nativePath, 'utf8') : '';
    const unmanaged = stripManagedCodexBlock(native);
    const codexServers = (await loadMcpRegistry()).servers.filter((item) => item.providers.includes('codex'));
    for (const server of codexServers) {
      const section = new RegExp(`^\\[mcp_servers\\.${server.id.replace(/[.*+?^${}()|[\\]\\]/g, '\\$&')}\\]`, 'm');
      if (section.test(unmanaged)) throw new Error(`Unmanaged Codex MCP server conflicts with managed id: ${server.id}`);
    }
    const blocks = codexServers.map((server) => renderMcpToml(server, roots));
    await atomicWrite(path.join(distRoot, 'codex', 'config.toml'), `${unmanaged}${unmanaged ? '\n\n' : ''}# BEGIN agent-config managed mcp\n${blocks.join('\n\n')}\n# END agent-config managed mcp\n`);
  }
  if (artifactIds.includes('provider.codex-hooks')) {
    const nextPath = path.join(sourceRoot, 'providers', 'codex', 'hooks.base.json');
    const previousPath = path.join(roots.AGENT_CONFIG_STATE_ROOT, 'active', 'source', 'providers', 'codex', 'hooks.base.json');
    const nativePath = path.join(roots.USER_HOME, '.codex', 'hooks.json');
    const previousRaw = await loadCodexHooks(previousPath, 'previous managed Codex hooks', { optional: true });
    const currentRaw = await loadCodexHooks(nativePath, 'native Codex hooks', { optional: true });
    const nextRaw = await loadCodexHooks(nextPath, 'next managed Codex hooks');
    const previous = expandKnownTokens(previousRaw ?? { hooks: {} }, roots);
    const current = currentRaw ?? { hooks: {} };
    const next = expandKnownTokens(nextRaw, roots);
    const merged = mergeCodexHooks(previous, current, next, { currentExists: currentRaw !== null });
    await atomicWrite(path.join(distRoot, 'codex', 'hooks.json'), canonicalize(merged));
  }
}

async function generateControllerRuntime(sourceRoot, distRoot) {
  const target = path.join(distRoot, 'controller', 'v0.1.0');
  await mkdir(path.join(target, 'scripts'), { recursive: true });
  await copyTree(path.join(sourceRoot, 'lib'), path.join(target, 'lib'));
  await atomicWrite(path.join(target, 'scripts', 'agent-config-controller.mjs'), await readFile(path.join(sourceRoot, 'scripts', 'agent-config-controller.mjs')));
  await atomicWrite(path.join(target, 'package.json'), await readFile(path.join(sourceRoot, 'package.json')));
}

// Contracts are text another repository owns and this one distributes. They are
// composed into an agent at render time rather than pasted into its prompt, so a
// bump upstream reaches every agent that declares it through one ordinary release.
async function loadContracts(sourceRoot) {
  const contractsRoot = path.join(sourceRoot, 'contracts');
  const contracts = new Map();
  if (!await pathExists(contractsRoot)) return contracts;
  for (const entry of await readdir(contractsRoot, { withFileTypes: true })) {
    if (!entry.isFile() || !entry.name.endsWith('.md') || entry.name === 'README.md') continue;
    const text = (await readFile(path.join(contractsRoot, entry.name), 'utf8')).trim();
    if (text) contracts.set(entry.name.slice(0, -'.md'.length), text);
  }
  return contracts;
}

function composeAgentBody(name, model, prompt, contracts) {
  const blocks = (model.contracts ?? []).map((id) => {
    const text = contracts.get(id);
    // Fail loudly. A silently dropped contract would ship an agent with no
    // cross-vault rules and nothing would report it.
    if (!text) throw new Error(`agents/${name}: declared contract not found in contracts/: ${id}`);
    return text;
  });
  return [...blocks, prompt.trim()].filter(Boolean).join('\n\n');
}

async function generateAgents(sourceRoot, distRoot) {
  const agentsRoot = path.join(sourceRoot, 'agents');
  if (!await pathExists(agentsRoot)) return [];
  const contracts = await loadContracts(sourceRoot);
  const generated = [];
  const entries = await readdir(agentsRoot, { withFileTypes: true });
  for (const entry of entries.filter((item) => item.isDirectory()).sort((a, b) => a.name.localeCompare(b.name))) {
    const root = path.join(agentsRoot, entry.name);
    const model = JSON.parse(await readFile(path.join(root, 'agent.json'), 'utf8'));
    const prompt = await readFile(path.join(root, 'prompt.md'), 'utf8');
    const body = composeAgentBody(entry.name, model, prompt, contracts);
    if (model.providers?.includes('claude')) {
      // tools before model, matching the key order these agents were authored in.
      const claude = `---\nname: ${entry.name}\ndescription: ${model.description}\n${model.claude?.tools ? `tools: ${model.claude.tools.join(', ')}\n` : ''}${model.claude?.model ? `model: ${model.claude.model}\n` : ''}---\n\n${body}\n`;
      const target = path.join(distRoot, 'claude', 'agents', `${entry.name}.md`);
      await atomicWrite(target, claude);
      generated.push(target);
    }
    if (model.providers?.includes('codex')) {
      const codex = [`name = ${tomlString(entry.name)}`, `description = ${tomlString(model.description)}`];
      if (model.codex?.model) codex.push(`model = ${tomlString(model.codex.model)}`);
      if (model.codex?.sandbox_mode) codex.push(`sandbox_mode = ${tomlString(model.codex.sandbox_mode)}`);
      codex.push(`developer_instructions = ${tomlString(body)}`);
      const target = path.join(distRoot, 'codex', 'agents', `${entry.name}.toml`);
      await atomicWrite(target, `${codex.join('\n')}\n`);
      generated.push(target);
    }
  }
  return generated;
}

export async function generateOutputs(sourceRoot, distRoot, roots = {}, { artifactIds = [] } = {}) {
  await mkdir(path.join(distRoot, 'claude'), { recursive: true });
  await mkdir(path.join(distRoot, 'codex'), { recursive: true });
  // Compose the Markdown inputs declared by the global instructions artifact.
  const manifest = JSON.parse(await readFile(path.join(sourceRoot, 'manifest.json'), 'utf8'));
  const instructions = manifest.artifacts.find((artifact) => artifact.id === 'instructions.global');
  const common = (instructions?.source ?? [])
    .filter((relative) => relative.endsWith('.md') && !/^providers\/(claude|codex)\/instructions\.append\.md$/.test(relative))
    .map((relative) => path.join(sourceRoot, relative));
  const claudeInstructions = await combineMarkdown([...common, path.join(sourceRoot, 'providers', 'claude', 'instructions.append.md')], 'Claude global instructions');
  const codexInstructions = await combineMarkdown([...common, path.join(sourceRoot, 'providers', 'codex', 'instructions.append.md')], 'Codex global instructions');
  await atomicWrite(path.join(distRoot, 'claude', 'CLAUDE.md'), claudeInstructions);
  await atomicWrite(path.join(distRoot, 'codex', 'AGENTS.md'), codexInstructions);
  await generateAgents(sourceRoot, distRoot);
  await generateProviderControl(sourceRoot, distRoot, roots, artifactIds);
  await generateControllerRuntime(sourceRoot, distRoot);
  const files = await listTree(distRoot);
  await atomicWrite(path.join(distRoot, 'provenance.json'), canonicalize({ schemaVersion: 1, generatorVersion: TOOL_VERSION, files }));
  return { files: await listTree(distRoot), digest: await hashTree(distRoot) };
}

export async function materializeWorkingTree(sourceRoot, destination) {
  await mkdir(destination, { recursive: true });
  await copyTree(sourceRoot, destination);
}
